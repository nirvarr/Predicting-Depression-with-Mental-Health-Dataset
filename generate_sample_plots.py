#!/usr/bin/env python3
"""
Generate placeholder images for the visualization gallery demonstration.
This creates sample PNG images to show how the gallery interface works.

NOTE: This is a demo/helper script. The actual plots will be generated by
the R script (depression_newdataset) when run with real data. This script
is only useful for testing the visualization gallery without running R.
"""

from PIL import Image, ImageDraw, ImageFont
import os

def create_placeholder(filename, title, width=800, height=600):
    """Create a placeholder image with title text."""
    # Create image with gradient background
    img = Image.new('RGB', (width, height), color='white')
    draw = ImageDraw.Draw(img)
    
    # Draw gradient background
    for y in range(height):
        r = int(100 + (155 * y / height))
        g = int(120 + (135 * y / height))
        b = int(200 + (55 * y / height))
        draw.rectangle([(0, y), (width, y+1)], fill=(r, g, b))
    
    # Add border
    draw.rectangle([(10, 10), (width-10, height-10)], outline='white', width=5)
    
    # Add title text in center
    try:
        # Try to use a default font, fallback to basic if not available
        font = ImageFont.truetype("/usr/share/fonts/truetype/dejavu/DejaVuSans-Bold.ttf", 40)
        small_font = ImageFont.truetype("/usr/share/fonts/truetype/dejavu/DejaVuSans.ttf", 20)
    except:
        font = ImageFont.load_default()
        small_font = ImageFont.load_default()
    
    # Draw title
    bbox = draw.textbbox((0, 0), title, font=font)
    text_width = bbox[2] - bbox[0]
    text_height = bbox[3] - bbox[1]
    x = (width - text_width) / 2
    y = (height - text_height) / 2 - 30
    
    # Draw shadow
    draw.text((x+3, y+3), title, fill=(0, 0, 0, 128), font=font)
    # Draw text
    draw.text((x, y), title, fill='white', font=font)
    
    # Draw subtitle
    subtitle = "Sample Visualization"
    bbox2 = draw.textbbox((0, 0), subtitle, font=small_font)
    text_width2 = bbox2[2] - bbox2[0]
    x2 = (width - text_width2) / 2
    y2 = y + text_height + 20
    draw.text((x2, y2), subtitle, fill=(255, 255, 255, 200), font=small_font)
    
    # Save image
    img.save(filename)
    print(f"Created: {filename}")

def main():
    """Generate all placeholder images."""
    plots_dir = "plots"
    os.makedirs(plots_dir, exist_ok=True)
    
    visualizations = [
        ("model_comparison_rmse.png", "Model RMSE", 1000, 600),
        ("model_comparison_r2.png", "Model R-Squared", 1000, 600),
        ("correlation_heatmap.png", "Correlation Heatmap", 800, 800),
        ("actual_vs_predicted_rf.png", "Actual vs Predicted", 800, 800),
        ("decision_tree.png", "Decision Tree", 1200, 800),
        ("feature_importance_rf.png", "Feature Importance", 900, 600),
        ("residuals_linear.png", "Residual Plot", 800, 600),
        ("model_metrics_comparison.png", "All Metrics", 1200, 800),
        ("distribution_comparison.png", "Distributions", 1000, 600),
    ]
    
    for filename, title, width, height in visualizations:
        filepath = os.path.join(plots_dir, filename)
        create_placeholder(filepath, title, width, height)
    
    print(f"\n✓ Generated {len(visualizations)} placeholder images in '{plots_dir}/' directory")
    print("✓ Open 'visualization_gallery.html' in a browser to view the gallery")

if __name__ == "__main__":
    main()
